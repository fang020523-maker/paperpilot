def inline(md: str) -> str:
    """行内 markdown → ReportLab 标记（转义 + 粗体 + 行内代码 + 链接）"""
    t = md.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    t = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r"\1", t)  # 链接只留文字
    t = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", t)
    t = re.sub(r"`([^`]+)`", r'<font face="SimHei" color="#206a85">\1</font>', t)
    return t

def make_table(rows):
    """md 表格 → ReportLab Table（Paragraph 单元格、比例列宽、居中、跨页表头）"""
    if len(rows) < 2:
        return None
    header = rows[0]
    body = [r for r in rows[2:]] if len(rows) > 2 and set("".join(rows[1])) <= set("-: ") else rows[1:]
    ncol = len(header)
    data = [[Paragraph(inline(c), S["cellh"]) for c in header]]
    for r in body:
        r = r + [""] * (ncol - len(r))
        data.append([Paragraph(inline(c), S["cell"]) for c in r[:ncol]])
    # 列宽：按各列最大字符宽估算权重（CJK 记 2）
    def w(cell):
        return sum(2 if ord(ch) > 0x2E80 else 1 for ch in re.sub(r"<[^>]+>", "", inline(cell)))
    weights = []
    for j in range(ncol):
        col = [header[j]] + [r[j] if j < len(r) else "" for r in body]
        weights.append(max(min(max(w(c) for c in col), 60), 4))
    total = sum(weights)
    col_w = [max(av * AVAIL_W / total, 0.09 * AVAIL_W) for av in weights]
    # 收敛到可用宽度
    scale = min(1.0, AVAIL_W / sum(col_w))
    col_w = [x * scale for x in col_w]
    tbl = Table(data, colWidths=col_w, repeatRows=1, hAlign="CENTER")
    style = [
        ("BACKGROUND", (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("LINEBELOW", (0, 0), (-1, 0), 0.7, ACCENT),
        ("LINEBELOW", (0, -1), (-1, -1), 0.5, BG_SURFACE),
        ("LINEABOVE", (0, 0), (-1, 0), 0.7, ACCENT),
    ]
    for i in range(1, len(data)):
        style.append(("BACKGROUND", (0, i), (-1, i), TABLE_ROW_EVEN if i % 2 else TABLE_ROW_ODD))
    tbl.setStyle(TableStyle(style))
    return tbl

