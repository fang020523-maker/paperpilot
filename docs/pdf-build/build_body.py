# Intent: neutral | Mode: minimal | Harmony: split_complementary
ACCENT       = colors.HexColor('#278eb0')
TEXT_PRIMARY = colors.HexColor('#1d1f20')
TEXT_MUTED   = colors.HexColor('#6e767a')
BG_SURFACE   = colors.HexColor('#d4dade')
BG_PAGE      = colors.HexColor('#eef0f1')
TABLE_HEADER_COLOR = ACCENT
TABLE_HEADER_TEXT  = colors.white
